package net.sourceforge.pmd.lang.java.symbols.internal.ast;

import static net.sourceforge.pmd.util.CollectionUtil.setOf;

import java.lang.reflect.Modifier;
import java.util.List;
import java.util.Map;
import java.util.Objects;

import net.sourceforge.pmd.lang.java.ast.ASTAnnotation;
import net.sourceforge.pmd.lang.java.ast.ASTAssignableExpr.ASTNamedReferenceExpr;
import net.sourceforge.pmd.lang.java.ast.ASTMemberValuePair;
import net.sourceforge.pmd.lang.java.ast.ASTPrimitiveType;
import net.sourceforge.pmd.lang.java.ast.ASTType;
import net.sourceforge.pmd.lang.java.ast.ASTTypeDeclaration;
import net.sourceforge.pmd.lang.java.ast.ASTVariableId;
import net.sourceforge.pmd.lang.java.ast.internal.JavaAstUtils;
import net.sourceforge.pmd.lang.java.internal.JavaAstProcessor;
import net.sourceforge.pmd.lang.java.symbols.JClassSymbol;
import net.sourceforge.pmd.lang.java.symbols.JFieldSymbol;
import net.sourceforge.pmd.lang.java.symbols.JMethodSymbol;
import net.sourceforge.pmd.lang.java.symbols.internal.ImplicitMemberSymbols;
import net.sourceforge.pmd.lang.java.types.JPrimitiveType.PrimitiveTypeKind;
import net.sourceforge.pmd.lang.java.types.Substitution;
import net.sourceforge.pmd.util.CollectionUtil;

/**
 * Creates the symbols for members that lombok generates, so that
 * they can be referenced from source code.
 *
 * @see AstClassSym#processLombok(JavaAstProcessor)
 */
final class LombokUtil {

    private static final String LOMBOK_GETTER = "lombok.Getter";
    private static final String LOMBOK_DATA = "lombok.Data";
    private static final String LOMBOK_VALUE = "lombok.Value";

    /**
     * Maps lombok logger annotations to the type of the field they generate.
     * {@code @CustomLog} is not included, as its type is defined in {@code lombok.config}.
     *
     * @see <a href="https://projectlombok.org/features/log">Lombok @Log</a>
     */
    private static final Map<String, String> LOMBOK_LOGGERS = CollectionUtil.buildMap(m -> {
        m.put("lombok.extern.slf4j.Slf4j", "org.slf4j.Logger");
        m.put("lombok.extern.slf4j.XSlf4j", "org.slf4j.ext.XLogger");
        m.put("lombok.extern.java.Log", "java.util.logging.Logger");
        m.put("lombok.extern.log4j.Log4j", "org.apache.log4j.Logger");
        m.put("lombok.extern.log4j.Log4j2", "org.apache.logging.log4j.Logger");
        m.put("lombok.extern.apachecommons.CommonsLog", "org.apache.commons.logging.Log");
        m.put("lombok.extern.jbosslog.JBossLog", "org.jboss.logging.Logger");
        m.put("lombok.extern.flogger.Flogger", "com.google.common.flogger.FluentLogger");
    });

    private LombokUtil() {
        // utility class
    }

    /**
     * Adds the fields and methods generated by lombok annotations on
     * the given type declaration to the given lists.
     */
    static void addLombokMembers(JClassSymbol classSym,
                                 ASTTypeDeclaration node,
                                 JavaAstProcessor processor,
                                 List<JFieldSymbol> declaredFields,
                                 List<JMethodSymbol> declaredMethods) {
        for (Map.Entry<String, String> logger : LOMBOK_LOGGERS.entrySet()) {
            if (node.isAnnotationPresent(logger.getKey())) {
                declaredFields.add(loggerField(classSym, processor, logger.getValue()));
                break;
            }
        }

        declaredFields.stream()
                .filter(f -> !f.isStatic())
                .map(f -> f.tryGetNode())
                .filter(Objects::nonNull)
                .filter(varId -> !varId.isRecordComponent())
                .forEach(varId -> {
                    ASTAnnotation fieldGetter = varId.getAnnotation(LOMBOK_GETTER);
                    int accessModifier = -1;

                    if (fieldGetter != null) {
                        accessModifier = getAccessModifier(fieldGetter);
                    } else {
                        ASTAnnotation classGetter = node.getAnnotation(LOMBOK_GETTER);
                        if (classGetter != null) {
                            accessModifier = getAccessModifier(classGetter);
                        } else if (JavaAstUtils.hasAnyAnnotation(node, setOf(LOMBOK_DATA, LOMBOK_VALUE))) {
                            accessModifier = Modifier.PUBLIC;
                        }
                    }

                    if (accessModifier != -1) {
                        JMethodSymbol getter = getter(classSym, (JFieldSymbol) varId.getSymbol(), accessModifier);
                        String getterName = getter.getSimpleName();
                        if (declaredMethods.stream().noneMatch(m -> m.getSimpleName().equals(getterName) && m.getArity() == 0)) {
                            declaredMethods.add(getter);
                        }
                    }
                });
    }

    /**
     * The {@code log} field generated by a lombok logger annotation
     * such as {@code @Slf4j} or {@code @Log4j2}.
     *
     * @param loggerClassName Binary name of the type of the logger
     */
    private static JFieldSymbol loggerField(JClassSymbol classSym, JavaAstProcessor processor, String loggerClassName) {
        return ImplicitMemberSymbols.fakeField(
                classSym,
                "log",
                Modifier.PRIVATE | Modifier.STATIC | Modifier.FINAL,
                (ts, s) ->
                    ts.declaration(processor.findSymbolCannotFail(loggerClassName))
        );
    }

    private static JMethodSymbol getter(JClassSymbol classSym, JFieldSymbol field, int accessModifier) {
        String fieldName = field.getSimpleName();
        String prefix = "get";
        ASTVariableId varId = field.tryGetNode();
        if (varId != null) {
            ASTType typeNode = varId.getTypeNode();
            if (typeNode instanceof ASTPrimitiveType
                    && ((ASTPrimitiveType) typeNode).getKind() == PrimitiveTypeKind.BOOLEAN) {
                prefix = "is";
            }
        }
        String name = prefix + Character.toUpperCase(fieldName.charAt(0)) + fieldName.substring(1);

        return ImplicitMemberSymbols.fakeMethod(
                classSym,
                name,
                accessModifier,
                (ts, s) -> field.getTypeMirror(Substitution.EMPTY)
        );
    }

    private static int getAccessModifier(ASTAnnotation annot) {
        return annot.getFlatValue(ASTMemberValuePair.VALUE_ATTR)
                .filter(v -> v instanceof ASTNamedReferenceExpr)
                .toStream()
                .map(ASTNamedReferenceExpr.class::cast)
                .map(ASTNamedReferenceExpr::getName)
                .findFirst()
                .map(accessLevel -> {
                    switch (accessLevel) {
                    case "PROTECTED":
                        return Modifier.PROTECTED;
                    case "PACKAGE":
                        return 0;
                    case "PRIVATE":
                        return Modifier.PRIVATE;
                    case "NONE":
                        return -1; // special value for NONE, we'll use -1 as a flag or handle it
                    case "PUBLIC":
                    default:
                        return Modifier.PUBLIC;
                    }
                })
                .orElse(Modifier.PUBLIC); // lombok generates by default public getters
    }
}
